import type { Word } from '../types'

function row(index: number, line: string): Word {
  const [hanzi, pinyin, ru, pos, exH, exP, exR, note] = line.split('|')
  const word: Word = {
    id: `l2:${String(index + 1).padStart(3, '0')}`,
    listId: 'lesson2',
    hanzi: hanzi.trim(),
    pinyin: pinyin.trim(),
    ru: ru.trim(),
    pos: pos.trim(),
    kind: 'vocab',
    example: { hanzi: exH.trim(), pinyin: exP.trim(), ru: exR.trim() },
  }
  if (note?.trim()) word.note = note.trim()
  return word
}


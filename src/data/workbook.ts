export type WorkTask = 'word' | 'stroke' | 'parts'

export type WorkItem = {
  id: string
  hanzi: string
  pinyin: string
  ru: string
  times: number
  page: number
  task: WorkTask
  hint?: string
}

export type WorkLesson = {
  id: string
  name: string
  title: string
  pages: string
  items: WorkItem[]
}

/** Пустые клетки справа от образца. По чертам их 4, в «напишите по частям» — 7. */
const STROKE = 4
const PARTS = 7

function row(
  lesson: number,
  task: WorkTask,
  index: number,
  hanzi: string,
  pinyin: string,
  ru: string,
  page: number,
  hint?: string,
): WorkItem {
  const times = task === 'stroke' ? STROKE : task === 'parts' ? PARTS : 1
  return { id: `w${lesson}-${task[0]}${String(index).padStart(2, '0')}`, hanzi, pinyin, ru, times, page, task, hint }
}

function words(lesson: number, page: number, rows: [string, string, string][]) {
  return rows.map(([hanzi, pinyin, ru], index) => row(lesson, 'word', index + 1, hanzi, pinyin, ru, page))
}

function strokes(lesson: number, page: number, rows: [string, string, string][]) {
  return rows.map(([hanzi, pinyin, ru], index) => row(lesson, 'stroke', index + 1, hanzi, pinyin, ru, page))
}

function parts(lesson: number, page: number, rows: [string, string, string, string][]) {
  return rows.map(([hanzi, pinyin, ru, hint], index) => row(lesson, 'parts', index + 1, hanzi, pinyin, ru, page, hint))
}


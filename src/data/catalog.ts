function vocab(line: string): Word {
  const [hanzi, pinyin, ru, pos, exH, exP, exR, note] = line.split('|')
  const word: Word = {
    id: `hsk:${hanzi.trim()}`,
    listId: 'hsk1',
    hanzi: hanzi.trim(),
    pinyin: pinyin.trim(),
    ru: ru.trim(),
    pos: pos.trim(),
    kind: 'vocab',
    example: { hanzi: exH.trim(), pinyin: exP.trim(), ru: exR.trim() },
  }
  if (note?.trim()) word.note = note.trim()
  return word
}

